        w('                if visit(d.tag_name) { return true; }');
        w('                if d.is_name_first { if visit(d.name) || d.type_expression.is_some_and(&mut *visit) { return true; } }');
        w('                else if d.type_expression.is_some_and(&mut *visit) || visit(d.name) { return true; }');
