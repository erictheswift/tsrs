const out: string[] = [];
const w = (s = '') => out.push(s);
const raw = (t: string) => {
    if (t === "&'static str") return "Text<'ast>";
    if (t === "&'static [P<Node>]") return "&'ast [NonNull<Node<'ast>>]";
    if (t === "&'static [&'static str]") return "&'ast [Text<'ast>]";
    if (t === "&'static dyn Any") return 'std::convert::Infallible';
    return t.replaceAll("'static", "'ast").replace(/P<(\w+)>/g, "NonNull<$1<'ast>>");
};
const native = (t: string) => {
    if (t === "&'static str") return "Text<'ast>";
    if (t === "&'static [&'static str]") return "&'ast [Text<'ast>]";
    if (t === "&'static dyn Any") return 'std::convert::Infallible';
    return t.replaceAll("'static", "'ast").replace(/P<(\w+)>/g, "&'ast $1<'ast>");
};
const conversion = (t: string, expr: string) => {
    const p = t.match(/^(Option<)?P<(\w+)>>?$/);
    const method: Record<string,string> = {Node:'node',NodeList:'list',ModifierList:'modifiers',Symbol:'symbol',SymbolTable:'table',FlowNode:'flow'};
    if (p) return p[1] ? `${expr}.map(|v| self.${method[p[2]]}(v))` : `self.${method[p[2]]}(${expr})`;
    if (t === "&'static [P<Node>]") return `self.nodes(${expr})`;
    if (t === "&'static str") return `self.text(${expr})`;
    if (t === "&'static [&'static str]") return `self.strings(${expr})`;
    if (t === "&'static dyn Any") return 'panic!("checker-only synthetic payload is outside the eager front end")';
    return expr;
};
