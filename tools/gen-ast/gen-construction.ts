// The same schema and record definitions as the published graph, with scoped construction borrows.
import * as fs from 'node:fs';
import * as path from 'node:path';
import { nodes, layouts, promoted, isEmptyLayout, factoryParams, snake, isNodeFlagsMember, flagConst, defaultValue, childMembers } from './gen-ast.ts';

const root = path.resolve(import.meta.dirname, '../../crates/tsrs_frontend_arena/src');
const records: { name: string; native: string; fields: { name: string; type: string }[] }[] = [];
const uninhabited = new Set<string>();
for (const module of ['model', 'metadata', 'generated']) {
    const text = fs.readFileSync(path.join(root, module + '.rs'), 'utf8');
    for (const match of text.matchAll(/record!\((\w+), \w+ \{\n([\s\S]*?)\n\}\);/g)) {
        // Reject syntax we cannot account for: silently dropping a field could leave padding that
        // becomes an uninitialized published field even when the overall size still matches.
        const fields = match[2].trim().split('\n').map(line => {
            const field = /^\s*(\w+): (.*?) => .+,$/.exec(line);
            if (!field) throw new Error(`unrecognized field in ${match[1]}: ${line}`);
            return { name: field[1], type: field[2] };
        }).filter(field => field.name !== 'lifetime');
        if (fields.length === 0) throw new Error(`empty or unrecognized record ${match[1]}`);
        if (fields.some(f => f.type === 'std::convert::Infallible')) uninhabited.add(match[1]);
        records.push({ name: match[1], native: `crate::${module}::${match[1]}<'static>`, fields });
    }
}
const graphType = new RegExp(`\\b(${records.map(r => r.name).concat('NodeData').join('|')})<'ast>`, 'g');
const building = (type: string) => {
    const result = type.replace(graphType, "$1<'build, 'ast>");
    return result.includes("'build") ? result.replaceAll("&'ast ", "&'build ") : result;
};
const fromLegacy = (type: string) => {
    if (type === "&'static str") return "Text<'ast>";
    if (type === "&'static [&'static str]") return "&'ast [Text<'ast>]";
    if (type === "&'static dyn Any") return 'std::convert::Infallible';
    return building(type.replaceAll("'static", "'ast").replace(/P<(\w+)>/g, "&'ast $1<'ast>"));
};
const out: string[] = [];
const w = (s = '') => out.push(s);
w('// Code generated by tools/gen-ast/gen-construction.ts. DO NOT EDIT.');
w('//! Mutable graph records available only inside `FileArena::build`.');
w('//! Every graph edge is an invariant construction borrow; publication freezes these same slots.');
w('use crate::factory::{construction_record, construction_entry};');
w('use crate::{FileReference, NodeFactory, Pragma, Text};');
w('use tsrs_ast::{CheckFlags, Kind, ModifierFlags, NodeFlags, SymbolFlags, TokenFlags};');
w('use tsrs_ast::flow::FlowFlags;');
w('use tsrs_core::TextRange;');
for (const record of records) {
    if (uninhabited.has(record.name)) continue;
    const entry = ['SymbolEntry', 'PatternAmbientModule'].includes(record.name);
    const method = (entry ? '' : 'alloc_') + snake(record.name);
    w(`${entry ? 'construction_entry' : 'construction_record'}!(${record.name}, ${record.native}, ${method} {`);
    for (const field of record.fields) {
        const setter = entry ? '' : `, set_${field.name.replace(/_$/, '')}`;
        w(`    ${field.name}${setter}: ${building(field.type)},`);
    }
    w('});');
}
w('#[repr(C, u16)]');
w('#[derive(Clone, Copy)]');
w("pub enum NodeData<'build, 'ast: 'build> {");
for (const node of nodes) {
    if (uninhabited.has(node.name)) {
        w('    // Checker-only payloads cannot be constructed; retain the published discriminant order.');
        w(`    ${node.name}(std::convert::Infallible),`);
    } else w(`    ${node.name}${isEmptyLayout(layouts.get(node.name)!) ? '' : `(&'build ${node.name}<'build, 'ast>)`},`);
}
for (const name of ['FlowSwitchClauseData', 'FlowReduceLabelData']) w(`    ${name}(&'build ${name}<'build, 'ast>),`);
w('}');
w("const _: () = assert!(std::mem::size_of::<NodeData<'static, 'static>>() == std::mem::size_of::<crate::NodeData<'static>>());");
w("const _: () = assert!(std::mem::align_of::<NodeData<'static, 'static>>() == std::mem::align_of::<crate::NodeData<'static>>());");
w("impl<'build, 'ast> NodeFactory<'build, 'ast> {");
for (const node of nodes) {
    // The source file additionally owns text/metadata. Its explicit constructor is handwritten.
    const fields = promoted(layouts.get(node.name)!);
    if (node.name === 'SourceFile' || fields.some(f => f.ty === "&'static dyn Any")) continue;
    const params = factoryParams(node);
    const values = new Map(params.filter(p => !p.m.isKindParam() && !isNodeFlagsMember(p.m))
        .map(p => [p.m.name, p.m.bitmask ? `${p.name} & ${flagConst(p.m.bitmask)}` : p.name]));
    for (const [name, kind] of [[node.name, node.syntaxKindName], ...node.kindAliases.map(a => [a, a])]) {
        const kindValue = params.some(p => p.m.isKindParam()) ? 'kind' : `Kind::${kind}`;
        w(`    pub fn new_${snake(name)}(&self${params.map(p => `, ${p.name}: ${fromLegacy(p.ty)}`).join('')}) -> &'build Node<'build, 'ast> {`);
        const data = isEmptyLayout(layouts.get(node.name)!) ? `NodeData::${node.name}` :
            `NodeData::${node.name}(self.alloc_${snake(node.name)}(${fields.map(f => values.get(f.name) ?? (f.ty === "&'static str" ? 'Text::default()' : defaultValue(f.ty))).join(', ')}))`;
        const flags = params.filter(p => isNodeFlagsMember(p.m));
        if (flags.length) {
            w(`        let node = self.new_node(${kindValue}, ${data});`);
            for (const flag of flags) w(`        node.set_flags(node.flags() | ${flag.m.bitmask ? `(${flag.name} & ${flagConst(flag.m.bitmask)})` : flag.name});`);
            w('        node');
        } else w(`        self.new_node(${kindValue}, ${data})`);
        w('    }');
    }
}
w('}');
// Construction getters preserve the schema's payload discrimination without exposing mutable cells.
w("impl<'build, 'ast> Node<'build, 'ast> {");
for (const node of nodes) {
    if (isEmptyLayout(layouts.get(node.name)!) || uninhabited.has(node.name)) continue;
    w(`    pub fn as_${snake(node.name)}(&self) -> &'build ${node.name}<'build, 'ast> {`);
    w(`        match self.data() { NodeData::${node.name}(data) => data, _ => panic!("expected ${node.name}") }`);
    w('    }');
}
w("    pub fn for_each_child(&self, visit: &mut impl FnMut(&'build Node<'build, 'ast>) -> bool) -> bool {");
w('        match self.data() {');
for (const node of nodes) {
    const fields = promoted(layouts.get(node.name)!);
    const children = childMembers(node);
    if (isEmptyLayout(layouts.get(node.name)!) || uninhabited.has(node.name) || !children.length) continue;
    w(`            NodeData::${node.name}(d) => {`);
    if (node.name === 'JSDocParameterOrPropertyTag') {
        w('                if visit(d.tag_name()) { return true; }');
        w('                if d.is_name_first() { if visit(d.name()) || d.type_expression().is_some_and(&mut *visit) { return true; } }');
        w('                else if d.type_expression().is_some_and(&mut *visit) || visit(d.name()) { return true; }');
        w('                d.comment().is_some_and(|l| l.nodes().iter().any(|&n| visit(n)))');
    } else {
        const tests = children.map(member => {
            const field = fields.find(f => f.name === member.name)!;
            const expr = `d.${field.rust}()`;
            if (field.ty === 'P<Node>') return `visit(${expr})`;
            if (field.ty === 'Option<P<Node>>') return `${expr}.is_some_and(&mut *visit)`;
            if (field.ty === "&'static [P<Node>]") return `${expr}.iter().any(|&n| visit(n))`;
            if (field.ty.startsWith('Option<')) return `${expr}.is_some_and(|l| l.nodes().iter().any(|&n| visit(n)))`;
            return `${expr}.nodes().iter().any(|&n| visit(n))`;
        });
        w('                ' + tests.join(' || '));
    }
    w('            }');
}
w('            _ => false,'); w('        }'); w('    }');
for (const name of ['symbol', 'locals', 'flow_node', 'text']) {
    const type: Record<string, string> = {symbol:"Option<&'build Symbol<'build, 'ast>>", locals:"Option<&'build SymbolTable<'build, 'ast>>", flow_node:"Option<&'build FlowNode<'build, 'ast>>", text:"Text<'ast>"};
    w(`    pub fn ${name}(&self) -> ${type[name]} {`); w('        match self.data() {');
    for (const node of nodes) if (promoted(layouts.get(node.name)!).some(f => f.rust === name && (name !== 'text' || f.ty === "&'static str"))) w(`            NodeData::${node.name}(data) => data.${name}(),`);
    w(`            _ => ${name === 'text' ? 'Text::default()' : 'None'},`); w('        }'); w('    }');
}
w('}');
fs.writeFileSync(path.join(root, 'construction.rs'), out.join('\n') + '\n');
console.log(`Wrote ${path.join(root, 'construction.rs')}`);
