    if (isEmptyLayout(layouts.get(n.name)!)) { w(`            (tsrs_ast::NodeData::${n.name}, NodeData::${n.name}) => {},`); continue; }
    if (promoted(layouts.get(n.name)!).some(f=>f.ty === "&'static dyn Any")) continue;
